create table if not exists public.saved_materials (
  id bigint generated by default as identity primary key,
  user_id text not null,
  fan text not null,
  sinf text not null,
  mavzu text not null,
  desc_text text,
  icon text,
  cover text,
  created_at timestamptz not null default now()
);

create index if not exists saved_materials_user_id_idx on public.saved_materials(user_id);
